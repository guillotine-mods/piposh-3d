def ensure_cache_warm(level: str) -> None:
    """Generates this level's own brush .glb (if missing) plus every MDL
    .glb referenced by it (if missing), via the same two offline scripts
    that used to populate assets/converted/ before this branch moved the
    shipped game to runtime WMB parsing. Self-healing: a fresh checkout, or
    a level nobody's opened in the viewer yet, "just works" on first
    request instead of needing a manual pre-conversion step remembered and
    run by hand."""
    import subprocess

    CACHE_DIR.mkdir(parents=True, exist_ok=True)
    brush_path = LEVEL_JSON_DIR / f"{level}_brush.glb"
    if not brush_path.exists():
        print(f"  [cache] generating brush geometry for {level}...")
        subprocess.run(
            [
                sys.executable,
                str(ROOT / "tools" / "extract_wmb_mesh.py"),
                "--only",
                level,
                "--dst-levels",
                str(LEVEL_JSON_DIR),
                "--dst-wmb",
                str(WMB_GLB_DIR),
            ],
            check=False,
            cwd=str(ROOT / "tools"),
        )

    wmb_path = None
    for ext in (".WMB", ".wmb"):
        cand = WMB_SRC_DIR / (level + ext)
        if cand.exists():
            wmb_path = cand
            break
    if wmb_path is None:
        return
    level_data = parse_wmb(wmb_path)
    stems = sorted(
        {
            Path(e["file"]).stem
            for e in level_data["entities"]
            if e["file"] and e["file"].lower().endswith(".mdl")
        }
    )
    missing = [s for s in stems if not (MDL_GLB_DIR / f"{s}.glb").exists()]
    if missing:
        print(f"  [cache] generating {len(missing)} character/prop model(s) for {level}...")
        subprocess.run(
            [
                sys.executable,
                str(ROOT / "tools" / "convert_mdl.py"),
                "--only",
                *missing,
                "--dst",
                str(MDL_GLB_DIR),
            ],
            check=False,
            cwd=str(ROOT / "tools"),
        )


# --- Light calibration, mirroring wmb_level_loader.gd's _spawn_light() /
# _cap_saturated_light_ranges() EXACTLY (GB-44 through GB-49's own real,
# shipped values) -- so what this viewer shows as each light's starting
# energy/range is the same number the real Godot game actually renders
# with, not the raw uncalibrated WMB value. Without this the viewer would
# be validating a fictional light setup nobody ships.
SATURATION_THRESHOLD = 0.3
COLOR_DIFF_THRESHOLD = 0.5
RANGE_CAP_FRACTION = 1.2
RANGE_CAP_FLOOR = 60.0
BASE_ENERGY = 1000.0
ENERGY_SCALE_REFERENCE_RANGE = 500.0
RANGE_CLAMP_MIN = 20.0
RANGE_CLAMP_MAX = 4000.0


def calibrate_lights(lights: list[dict]) -> None:
    """Mutates each light dict in place, adding `calibrated_range` and
    `calibrated_energy` -- the actual values the real Godot game's
    `_spawn_light()` would compute for this exact light, given every other
    light in the same level (the saturated-color anti-bleed cap needs the
    whole level's own light list, not just one light in isolation)."""
    for light in lights:
        rng = float(light.get("range", 300.0))
        light["raw_range"] = rng
        light["calibrated_range"] = max(RANGE_CLAMP_MIN, min(rng, RANGE_CLAMP_MAX))
        energy_scale = min(1.0, ENERGY_SCALE_REFERENCE_RANGE / max(rng, 1.0))
        light["calibrated_energy"] = BASE_ENERGY * energy_scale

    saturated = []
    for light in lights:
        c = light["color"]
        sat = max(c) - min(c)
        if sat > SATURATION_THRESHOLD:
            saturated.append(light)

    for i, li in enumerate(saturated):
        nearest = math.inf
        for j, lj in enumerate(saturated):
            if i == j:
                continue
            cd = math.dist(li["color"], lj["color"])
            if cd <= COLOR_DIFF_THRESHOLD:
                continue
            d = math.dist(li["pos"], lj["pos"])
            nearest = min(nearest, d)
        if nearest < math.inf:
            cap = max(nearest * RANGE_CAP_FRACTION, RANGE_CAP_FLOOR)
            li["calibrated_range"] = min(li["calibrated_range"], cap)


# --- Fresh WMB parse (independent of tools/extract_wmb_full.py) -----------


def _c_str(raw: bytes) -> str:
    return raw.split(b"\x00", 1)[0].decode("latin-1", errors="replace")


def _read_lists(data: bytes, n: int = 20) -> list[tuple[int, int]]:
    """WMB directory: a fixed-size table of (offset, length) pairs right
    after the 4-byte magic. Every chunk (objects, planes, textures, ...) is
    addressed through this table -- list index 15 is the object list for
    the WMB5 layout this game uses (confirmed by extract_wmb_full.py
    working across all 57 levels; re-verified here independently by
    checking every list's offset+length stays in-bounds)."""
    lists: list[tuple[int, int]] = []
    off = 4
    for _ in range(n):
        if off + 8 > len(data):
            break
        lo, ln = struct.unpack_from("<II", data, off)
        off += 8
        if ln == 0 and lo == 0:
            lists.append((lo, ln))
            continue
        if lo >= len(data) or lo + ln > len(data):
            break
        lists.append((lo, ln))
    return lists


def pos_gs_to_three(x: float, y: float, z: float) -> list[float]:
    """Acknex RHZUP (+X east, +Y north, +Z up) -> right-handed Y-up.
    Same target space as Godot: (x, y, z)_gs -> (x, z, -y). Three.js is
    also right-handed Y-up, so this is directly usable with no extra flip.
    """
    return [float(x), float(z), float(-y)]


def scale_gs_to_three(sx: float, sy: float, sz: float) -> list[float]:
    return [float(sx), float(sz), float(sy)]


def _norm_tilt(tilt_deg: float) -> float:
    t = float(tilt_deg)
    if t > 180.0:
        t -= 360.0
    elif t < -180.0:
        t += 360.0
    return t


def entity_basis_columns(pan_deg: float, tilt_deg: float, roll_deg: float) -> list[float]:
    """Conitec ang_to_matrix (DirectX Y-up), conjugated by S=diag(1,1,-1)
    into a right-handed Y-up basis -- same target convention as Godot's
    Basis(x_g, y_g, z_g). Returned as 9 floats, column-major: local +X,
    +Y, +Z axes expressed in world space. Local +X is "forward" by the
    whole pipeline's convention (WED pan=0 -> +X)."""
    p = math.radians(float(pan_deg))
    t = math.radians(_norm_tilt(tilt_deg))
    r = math.radians(float(roll_deg))
    cp, sp = math.cos(p), math.sin(p)
    ct, st = math.cos(t), math.sin(t)
    cr, sr = math.cos(r), math.sin(r)
    x_dx = (ct * cp, st, ct * sp)
    y_dx = (-cr * st * cp + sr * sp, cr * ct, -cr * st * sp - sr * cp)
    z_dx = (-sr * st * cp - cr * sp, sr * ct, cr * cp - sr * st * sp)
    x_g = (x_dx[0], x_dx[1], -x_dx[2])
    y_g = (y_dx[0], y_dx[1], -y_dx[2])
    z_g = (-z_dx[0], -z_dx[1], z_dx[2])
    return [*x_g, *y_g, *z_g]


_YAW_ALLOWLIST_PATH = ROOT / "tools" / "mdl_yaw_allowlist.json"
_yaw_allowlist_cache: dict[str, float] | None = None


def yaw_allowlist() -> dict[str, float]:
    """`extra_yaw_deg` from mdl_yaw_allowlist.json (same file convert_mdl.py
    reads), keyed lowercase stem -- read fresh here too rather than assumed,
    since the arrow gizmo needs to know about it: this correction is baked
    directly into the .glb's vertex data at convert time, so a mesh and the
    "raw pan/tilt/roll" arrow will *always* disagree by this amount for any
    allowlisted model unless the arrow also accounts for it."""
    global _yaw_allowlist_cache
    if _yaw_allowlist_cache is None:
        try:
            data = json.loads(_YAW_ALLOWLIST_PATH.read_text())
            _yaw_allowlist_cache = {k.lower(): float(v) for k, v in data.get("extra_yaw_deg", {}).items()}
        except Exception:
            _yaw_allowlist_cache = {}
    return _yaw_allowlist_cache


def yaw_rotate_y_three(v: tuple[float, float, float], deg: float) -> tuple[float, float, float]:
    """Same rotation convert_mdl.py's _yaw_rotate_y applies to mesh vertices
    (right-handed Y-up, rotate about +Y) -- used here to compute what
    direction the *mesh itself* (after its baked-in allowlist correction)
    actually points, for the arrow gizmo."""
    a = math.radians(deg)
    c, s = math.cos(a), math.sin(a)
    x, y, z = v
    return (x * c + z * s, y, -x * s + z * c)


# --- Feet-snap policy, fresh port of _should_feet_snap in
# scripts/engine/wmb_level_loader.gd (see docs/CONTRACT.md #3) -- entities
# are placed at their raw WED origin by default here, same as this whole
# tool's philosophy of showing raw parsed data, but without any floor
# correction at all every character appears to float/sink relative to
# where the actual game puts them. Ported so the viewer matches Godot's
# real spawn behavior instead of looking wrong in a *third*, new way.
_CAMERA_ACTIONS = {
    "cam", "thecam", "thecam2", "farcam", "scam", "cammy", "lookatme",
    "mycamera", "pipicam", "cam2", "cam3", "cam4", "camplane", "cameraengine",
}
_FEET_SNAP_EXCLUDE_STEMS = {
    "glass", "b747", "tv", "island", "headphon", "biplane",
    "biplane2", "hanger", "towerw", "dutyfree",
}


def should_feet_snap(action: str, stem: str) -> bool:
    a = action.lower()
    s = stem.lower()
    if a in _CAMERA_ACTIONS or s == "cam":
        return False
    if s in {"afg", "shiknote"}:
        return False
    if a == "window":
        return False
    if s in _FEET_SNAP_EXCLUDE_STEMS:
        return False
    if a in {"headphone", "land", "wind", "ent_rotate", "item_pickup"}:
        return False
    return True


def _make_entity_dict(
    name: str, filename: str, action: str,
    ox: float, oy: float, oz: float,
    pan: float, tilt: float, roll: float,
    sx: float, sy: float, sz: float,
    skills: list[float], flags: int,
) -> dict:
    stem = Path(filename).stem.lower() if filename else ""
    mesh_yaw = yaw_allowlist().get(stem, 0.0)
    basis = entity_basis_columns(pan, tilt, roll)
    x_col = basis[0:3]
    y_col = basis[3:6]
    z_col = basis[6:9]
    # Arrow direction = entity basis applied to the mesh's OWN forward,
    # which includes any baked-in mdl_yaw_allowlist.json correction --
    # without this the arrow only shows the raw WMB pan and will disagree
    # with the mesh by exactly the allowlist amount even when everything
    # is working correctly (this was the source of a false-positive "mesh
    # doesn't match arrow" report -- see docs/SESSION_LOG.md 2026-07-27).
    local_fwd = yaw_rotate_y_three((1.0, 0.0, 0.0), mesh_yaw)
    forward = [
        local_fwd[0] * x_col[0] + local_fwd[1] * y_col[0] + local_fwd[2] * z_col[0],
        local_fwd[0] * x_col[1] + local_fwd[1] * y_col[1] + local_fwd[2] * z_col[1],
        local_fwd[0] * x_col[2] + local_fwd[1] * y_col[2] + local_fwd[2] * z_col[2],
    ]
    return {
        "name": name,
        "file": filename,
        "action": action,
        "pos": pos_gs_to_three(ox, oy, oz),
        "pan_tilt_roll_gs": [float(pan), float(tilt), float(roll)],
        "scale": scale_gs_to_three(sx, sy, sz),
        "skills": skills,
        "flags": int(flags),
        "basis": basis,
        "mesh_yaw_deg": mesh_yaw,
        "forward": forward,
        "should_feet_snap": should_feet_snap(action, stem),
    }


def parse_wmb(path: Path) -> dict:
    data = path.read_bytes()
    magic = data[:4]
    lists = _read_lists(data)
    if len(lists) <= 15 or lists[15][1] == 0:
        raise ValueError(f"{path.name}: no object list found (list 15 empty)")

    base, length = lists[15]
    chunk = memoryview(data)[base : base + length]
    count = struct.unpack_from("<I", chunk, 0)[0]
    offsets = list(struct.unpack_from(f"<{count}I", chunk, 4))

    entities: list[dict] = []
    lights: list[dict] = []
    paths: list[dict] = []

    for rel in offsets:
        o = rel
        if o + 4 > len(chunk):
            continue
        typ = struct.unpack_from("<I", chunk, o)[0]
        o += 4

        if typ == 2:  # LIGHT
            ox, oy, oz = struct.unpack_from("<3f", chunk, o)
            o += 12
            r, g, b, rng = struct.unpack_from("<4f", chunk, o)
            lights.append(
                {
                    "pos": pos_gs_to_three(ox, oy, oz),
                    "color": [r / 100.0, g / 100.0, b / 100.0],
                    "range": float(rng),
                }
            )
            continue

        if typ == 6:  # PATH
            try:
                name = _c_str(bytes(chunk[o : o + 20]))
                o += 20
                fnum = struct.unpack_from("<f", chunk, o)[0]
                o += 4
                o += 12  # unused[3]
                num_edges = struct.unpack_from("<I", chunk, o)[0]
                o += 4
                npoints = int(fnum) if fnum >= 1.0 else int(num_edges)
                points = []
                for _ in range(max(npoints, 0)):
                    if o + 12 > len(chunk):
                        break
                    px, py, pz = struct.unpack_from("<3f", chunk, o)
                    o += 12
                    points.append(pos_gs_to_three(px, py, pz))
                paths.append({"name": name or f"path_{len(paths) + 1}", "points": points})
            except struct.error:
                pass
            continue

        if typ == 3:  # OLD ENTITY
            ox, oy, oz = struct.unpack_from("<3f", chunk, o)
            o += 12
            pan, tilt, roll = struct.unpack_from("<3f", chunk, o)
            o += 12
            sx, sy, sz = struct.unpack_from("<3f", chunk, o)
            o += 12
            name = _c_str(bytes(chunk[o : o + 20]))
            o += 20
            filename = _c_str(bytes(chunk[o : o + 13]))
            o += 13
            action = _c_str(bytes(chunk[o : o + 20]))
            o += 20
            o += 3  # pad (float-aligns the skills block)
            skills = list(struct.unpack_from("<8f", chunk, o))
            o += 32
            flags = struct.unpack_from("<I", chunk, o)[0] if o + 4 <= len(chunk) else 0
            entities.append(
                _make_entity_dict(name, filename, action, ox, oy, oz, pan, tilt, roll, sx, sy, sz, skills, flags)
            )
            continue

        if typ == 7:  # ENTITY (new format)
            ox, oy, oz = struct.unpack_from("<3f", chunk, o)
            o += 12
            pan, tilt, roll = struct.unpack_from("<3f", chunk, o)
            o += 12
            sx, sy, sz = struct.unpack_from("<3f", chunk, o)
            o += 12
            name = _c_str(bytes(chunk[o : o + 33]))
            o += 33
            filename = _c_str(bytes(chunk[o : o + 33]))
            o += 33
            action = _c_str(bytes(chunk[o : o + 33]))
            o += 34
            skills = list(struct.unpack_from("<20f", chunk, o))
            o += 80
            flags = struct.unpack_from("<I", chunk, o)[0]
            o += 4
            entities.append(
                _make_entity_dict(name, filename, action, ox, oy, oz, pan, tilt, roll, sx, sy, sz, skills, flags)
            )
            continue

    return {
        "source": path.name,
        "magic": magic.decode("ascii", "replace"),
        "entities": entities,
        "lights": lights,
        "paths": paths,
    }


