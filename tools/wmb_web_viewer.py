class Handler(BaseHTTPRequestHandler):
    # Small in-process cache -- parsing + calibrating a level is fast
    # (well under a second) but there's no reason to redo it on every
    # dropdown flick back to a level already visited this session.
    _level_cache: dict[str, dict] = {}

    def __init__(self, *args, levels: list[str], initial_level: str, **kwargs):
        self._levels = levels
        self._initial_level = initial_level
        super().__init__(*args, **kwargs)

    def log_message(self, fmt, *args):  # quieter console
        pass

    def _send_bytes(self, data: bytes, content_type: str) -> None:
        self.send_response(200)
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(len(data)))
        self.send_header("Access-Control-Allow-Origin", "*")
        self.end_headers()
        self.wfile.write(data)

    def _send_file(self, path: Path, content_type: str) -> None:
        if not path.exists():
            self.send_error(404)
            return
        self._send_bytes(path.read_bytes(), content_type)

    def _get_level(self, level: str) -> dict | None:
        if level not in self._levels:
            return None
        if level not in Handler._level_cache:
            print(f"Loading {level}...")
            Handler._level_cache[level] = load_level(level)
        return Handler._level_cache[level]

    def do_GET(self) -> None:  # noqa: N802
        parsed = urlparse(self.path)
        path = unquote(parsed.path)
        query = {k: v[-1] for k, v in parse_qs(parsed.query).items()}

        if path == "/" or path == "":
            level = query.get("level", self._initial_level)
            if level not in self._levels:
                level = self._initial_level
            # Plain .replace(), not .format() -- the HTML/CSS/JS below is
            # full of literal `{...}` (CSS rules, JS objects, the import
            # map) that .format() would try to parse as placeholders and
            # crash on (this broke every request to "/" the first time).
            html = VIEWER_HTML.replace("__LEVEL__", level).replace(
                "__LEVEL_OPTIONS__",
                "\n".join(
                    f'<option value="{lvl}"{" selected" if lvl == level else ""}>{lvl}</option>' for lvl in self._levels
                ),
            )
            self._send_bytes(html.encode("utf-8"), "text/html; charset=utf-8")
        elif path == "/api/level.json":
            level = query.get("level", self._initial_level)
            try:
                data = self._get_level(level)
            except Exception as exc:  # noqa: BLE001 -- surface any parse error to the browser, not a bare 500
                self._send_bytes(json.dumps({"error": str(exc)}).encode("utf-8"), "application/json")
                return
            if data is None:
                self.send_error(404, f"Unknown level {level!r}")
                return
            self._send_bytes(json.dumps(data).encode("utf-8"), "application/json")
        elif path.startswith("/mdl-glb/"):
            self._send_file(MDL_GLB_DIR / path[len("/mdl-glb/") :], "model/gltf-binary")
        elif path.startswith("/wmb-glb/"):
            self._send_file(WMB_GLB_DIR / path[len("/wmb-glb/") :], "model/gltf-binary")
        elif path.startswith("/brush-glb/"):
            self._send_file(LEVEL_JSON_DIR / path[len("/brush-glb/") :], "model/gltf-binary")
        else:
            self.send_error(404)


def list_available_levels() -> list[str]:
    if not WMB_SRC_DIR.exists():
        return []
    return sorted({p.stem for p in WMB_SRC_DIR.glob("*.[Ww][Mm][Bb]")}, key=str.lower)


def load_level(level: str) -> dict:
    wmb_path = None
    for ext in (".WMB", ".wmb"):
        cand = WMB_SRC_DIR / (level + ext)
        if cand.exists():
            wmb_path = cand
            break
    if wmb_path is None:
        raise FileNotFoundError(f"Could not find {level}.WMB under {WMB_SRC_DIR}")

    ensure_cache_warm(level)
    level_data = parse_wmb(wmb_path)
    calibrate_lights(level_data["lights"])

    mdl_index = _build_index(MDL_GLB_DIR)
    wmb_index = _build_index(WMB_GLB_DIR)
    for ent in level_data["entities"]:
        ent["model_url"] = resolve_model_url(ent["file"], mdl_index, wmb_index)

    brush_path = LEVEL_JSON_DIR / f"{level}_brush.glb"
    level_data["brush_url"] = f"/brush-glb/{level}_brush.glb" if brush_path.exists() else None
    return level_data


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "level",
        nargs="?",
        default="Start",
        help="Initial level to show, e.g. Start -- switch levels live in the browser afterward, no restart needed",
    )
    ap.add_argument("--port", type=int, default=8765)
    ap.add_argument("--no-browser", action="store_true")
    args = ap.parse_args()

    levels = list_available_levels()
    if not levels:
        print(f"No .WMB files found under {WMB_SRC_DIR}", file=sys.stderr)
        return 1
    initial = args.level if args.level in levels else levels[0]

    handler_cls = partial(Handler, levels=levels, initial_level=initial)
    server = ThreadingHTTPServer(("127.0.0.1", args.port), handler_cls)
    url = f"http://127.0.0.1:{args.port}/?level={initial}"
    print(f"{len(levels)} levels available. Serving on {url}  (Ctrl+C to stop)")
    print("Switch levels live via the in-page dropdown -- no server restart needed.")
    if not args.no_browser:
        threading.Timer(0.5, lambda: webbrowser.open(url)).start()
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
